import { createHash } from "node:crypto";
import { mkdir, readFile, readdir, rm, writeFile } from "node:fs/promises";
import { basename, join, resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const check = process.argv.slice(2).includes("--check");
const unsupported = process.argv.slice(2).filter((argument) => argument !== "--check");
if (unsupported.length > 0) {
  throw new Error(`unsupported option(s): ${unsupported.join(", ")}`);
}

const outputRoot = join(root, "packages/vscode/licenses");
const textRoot = join(outputRoot, "texts");
const bundlePath = join(root, "packages/vscode/dist/extension.bundle.cjs");
const packageLockPath = join(root, "package-lock.json");

function sha256(value) {
  return createHash("sha256").update(value).digest("hex");
}

function packageLocationsFromBundle(bundle) {
  const packages = new Map();
  const pattern = /^\/\/#region (\S+)/gmu;
  for (const match of bundle.matchAll(pattern)) {
    const modulePath = match[1];
    const marker = "node_modules/";
    const markerIndex = modulePath.lastIndexOf(marker);
    if (markerIndex === -1) continue;
    const prefix = modulePath.slice(0, markerIndex + marker.length);
    const segments = modulePath.slice(markerIndex + marker.length).split("/");
    const name = segments[0].startsWith("@") ? `${segments[0]}/${segments[1]}` : segments[0];
    const installPath = `${prefix}${name}`;
    if (
      installPath.startsWith("/") ||
      installPath.split("/").some((segment) => segment === "." || segment === "..")
    ) {
      throw new Error(
        `bundle region ${modulePath} is not repository-root-relative; rebuild with npm run build:editor`,
      );
    }
    packages.set(installPath, { installPath, name });
  }
  if (packages.size === 0) throw new Error("VS Code bundle has no attributable npm regions");
  return [...packages.values()].sort((left, right) =>
    left.installPath.localeCompare(right.installPath),
  );
}

function encodedPackageDirectory(name, version, installPath) {
  const rootInstall = `node_modules/${name}`;
  const locationSuffix = installPath === rootInstall ? "" : `-${sha256(installPath).slice(0, 8)}`;
  return `${name.replace("/", "__")}@${version}${locationSuffix}`;
}

function renderReport(inventory) {
  const rows = inventory.packages.map(
    (dependency) =>
      `| ${dependency.name} | ${dependency.version} | ${dependency.license} | \`${dependency.licenseTextSha256}\` | \`${dependency.integrity}\` |`,
  );
  return `# VS Code client bundle dependency licenses

This report is generated by \`scripts/generate-vscode-license-inventory.mjs\`
from Rolldown's module-region markers, the committed npm lockfile, and each
installed package's actual license text. Do not edit it by hand.

- Bundle: \`packages/vscode/dist/extension.bundle.cjs\`
- Bundle SHA-256: \`${inventory.bundleSha256}\`
- package-lock.json SHA-256: \`${inventory.packageLockSha256}\`
- Bundled third-party packages: ${inventory.packageCount}

Every listed license/copyright text is shipped byte-exactly below
\`packages/vscode/licenses/texts/\`. The generator fails closed when a new
bundle package or license expression appears.

| Package | Version | License | License-text SHA-256 | npm integrity |
| --- | --- | --- | --- | --- |
${rows.join("\n")}
`;
}

async function legalFilesFor(packageDirectory) {
  const candidates = (await readdir(packageDirectory, { withFileTypes: true }))
    .filter(
      (entry) =>
        entry.isFile() &&
        /^(?:licen[cs]e|copying|notice|copyright)(?:\.|$)/iu.test(entry.name),
    )
    .map((entry) => entry.name)
    .sort();
  if (!candidates.some((name) => /^(?:licen[cs]e|copying)(?:\.|$)/iu.test(name))) {
    throw new Error(
      `${packageDirectory} must expose a top-level license/copying text; found ${candidates.join(", ") || "none"}`,
    );
  }
  return candidates;
}

const [bundle, packageLockText, policyText] = await Promise.all([
  readFile(bundlePath, "utf8"),
  readFile(packageLockPath, "utf8"),
  readFile(join(outputRoot, "allowed-license-expressions.json"), "utf8"),
]);
const packageLock = JSON.parse(packageLockText);
const policy = JSON.parse(policyText);
const allowed = new Set(policy.allowedExpressions);
const packages = [];
const textOutputs = new Map();

for (const { installPath, name } of packageLocationsFromBundle(bundle)) {
  const packageDirectory = join(root, ...installPath.split("/"));
  const manifest = JSON.parse(await readFile(join(packageDirectory, "package.json"), "utf8"));
  const locked = packageLock.packages[installPath];
  if (!locked || locked.version !== manifest.version) {
    throw new Error(`${name}@${manifest.version} does not match package-lock.json`);
  }
  if (!manifest.license || manifest.license !== locked.license) {
    throw new Error(`${name}@${manifest.version} has inconsistent package/lock license metadata`);
  }
  if (!allowed.has(manifest.license)) {
    throw new Error(`${name}@${manifest.version} has unreviewed license: ${manifest.license}`);
  }
  if (!locked.integrity) throw new Error(`${name}@${manifest.version} has no npm integrity`);
  const legalFiles = await legalFilesFor(packageDirectory);
  const directory = encodedPackageDirectory(name, manifest.version, installPath);
  const legalTexts = [];
  for (const legalFile of legalFiles) {
    const legalText = await readFile(join(packageDirectory, legalFile));
    const relativeTextPath = join("texts", directory, legalFile);
    textOutputs.set(relativeTextPath, legalText);
    legalTexts.push({
      path: relativeTextPath.replaceAll("\\", "/"),
      sha256: sha256(legalText),
    });
  }
  const licenseText = legalTexts.find((text) =>
    /\/(?:licen[cs]e|copying)(?:\.|$)/iu.test(text.path),
  );
  packages.push({
    name,
    version: manifest.version,
    installPath,
    license: manifest.license,
    resolved: locked.resolved,
    integrity: locked.integrity,
    licenseTextPath: licenseText.path,
    licenseTextSha256: licenseText.sha256,
    legalTexts,
  });
}

const inventory = {
  schemaVersion: 1,
  generatedBy: "scripts/generate-vscode-license-inventory.mjs",
  bundle: "packages/vscode/dist/extension.bundle.cjs",
  bundleSha256: sha256(bundle),
  packageLockSha256: sha256(packageLockText),
  packageCount: packages.length,
  packages,
};
const outputs = new Map([
  ["bundle-dependencies.json", `${JSON.stringify(inventory, null, 2)}\n`],
  ["BUNDLE_DEPENDENCIES.md", renderReport(inventory)],
  ...textOutputs,
]);

if (check) {
  for (const [path, expected] of outputs) {
    const actual = await readFile(join(outputRoot, path)).catch(() => null);
    if (!actual || !Buffer.from(expected).equals(actual)) {
      throw new Error(`${join("packages/vscode/licenses", path)} is stale; run npm run licenses:vscode:generate`);
    }
  }
  const expectedDirectories = new Set(
    packages.map((dependency) =>
      encodedPackageDirectory(dependency.name, dependency.version, dependency.installPath),
    ),
  );
  const actualDirectories = new Set(await readdir(textRoot).catch(() => []));
  assertSameEntries(actualDirectories, expectedDirectories, "generated VS Code license directories");
} else {
  await rm(textRoot, { recursive: true, force: true });
  for (const [path, contents] of outputs) {
    const absolute = join(outputRoot, path);
    await mkdir(join(absolute, ".."), { recursive: true });
    await writeFile(absolute, contents);
  }
}

function assertSameEntries(actual, expected, label) {
  const extra = [...actual].filter((entry) => !expected.has(entry));
  const missing = [...expected].filter((entry) => !actual.has(entry));
  if (extra.length > 0 || missing.length > 0) {
    throw new Error(`${label} drifted; extra=${extra.join(",")} missing=${missing.join(",")}`);
  }
}

process.stdout.write(
  `${check ? "verified" : "generated"} ${packages.length} bundled VS Code dependency licenses\n`,
);
