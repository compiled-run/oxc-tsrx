// Generates docs/projection-example.json for the projection explorer:
// the authored TSRX, the REAL lint projection from tsrx_syntax (via
// docs/tools/projection-dump), and the REAL oxc-tsrx diagnostics for it.
// Prereqs:
//   cargo build --release --manifest-path docs/tools/projection-dump/Cargo.toml
//   cargo build --release --locked -p oxc_tsrx_cli --bins
import { execFileSync, spawnSync } from 'node:child_process'
import { mkdtempSync, mkdirSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const docsDir = path.dirname(fileURLToPath(import.meta.url))
const repoRoot = path.join(docsDir, '..')
const projectionBin = path.join(docsDir, 'tools', 'projection-dump', 'target', 'release', 'projection-dump')
const lintBin = path.join(repoRoot, 'target', 'release', 'oxc-tsrx')
const formatBin = path.join(repoRoot, 'target', 'release', 'oxc-tsrx-fmt')
const npmLintBin = path.join(repoRoot, 'packages', 'oxlint', 'bin', 'oxlint')

const tsrx = `export function Cart({ items }: Props) @{
  var total = 0;
  debugger;

  <section class="cart">
    @if (items.length > 0) {
      @for (const item of items; key item.id) {
        <Row item={item} />
      }
    } @else {
      <Empty />
    }
  </section>
}`

const projected = JSON.parse(
  execFileSync(projectionBin, [], { input: tsrx, encoding: 'utf8' }),
)
if (projected.error) throw new Error(`projection failed: ${projected.error}`)

const tmpDir = mkdtempSync(path.join(tmpdir(), 'oxc-tsrx-docs-'))
const relativeFile = path.join('src', 'Cart.tsrx')
mkdirSync(path.join(tmpDir, 'src'), { recursive: true })
writeFileSync(path.join(tmpDir, relativeFile), tsrx)

function runForTranscript(binary, args, env = process.env) {
  const result = spawnSync(binary, args, { cwd: tmpDir, encoding: 'utf8', env })
  if (result.error) throw result.error
  if (result.signal) throw new Error(`${path.basename(binary)} exited on signal ${result.signal}`)
  return `${result.stdout}${result.stderr}`
}

let report
let transcript
try {
  const lintOutput = execFileSync(
    lintBin,
    ['--format=json', '--deny', 'no-debugger', relativeFile],
    {
      cwd: tmpDir,
      encoding: 'utf8',
    },
  )
  report = JSON.parse(lintOutput)
} catch (error) {
  // Exit 1 means diagnostics were found. The JSON report is still complete.
  report = JSON.parse(error.stdout)
}

try {
  transcript = [
    {
      command: 'npx oxlint src/Cart.tsrx',
      output: runForTranscript(process.execPath, [npmLintBin, relativeFile], {
        ...process.env,
        OXC_TSRX_LINT_BIN: lintBin,
      }),
    },
    {
      command: 'npx oxfmt --check src/Cart.tsrx',
      output: runForTranscript(formatBin, ['--check', relativeFile]),
    },
  ]
} finally {
  rmSync(tmpDir, { recursive: true, force: true })
}

const example = {
  note: 'Generated by docs/generate-projection.mjs from the real tsrx_syntax projection and oxc-tsrx diagnostics. Do not edit by hand.',
  tsrx,
  projected: projected.projected,
  tokens: projected.tokens,
  transcript,
  diagnostics: report.diagnostics.map((diagnostic) => ({
    rule: diagnostic.rule,
    code: diagnostic.code,
    severity: diagnostic.severity,
    message: diagnostic.message,
    labels: diagnostic.labels,
  })),
}
writeFileSync(
  path.join(docsDir, 'projection-example.json'),
  `${JSON.stringify(example, null, 2)}\n`,
)
console.log(
  `wrote docs/projection-example.json (${example.diagnostics.length} diagnostics, ${example.transcript.length} transcript entries, projection ${example.projected.length} bytes)`,
)
